"""Local demo FastAPI frontend, built on the existing LangGraph/MCP agent."""
from __future__ import annotations

import json
import logging
import sys
from functools import lru_cache
from pathlib import Path
from threading import RLock
from uuid import UUID

from fastapi import FastAPI, HTTPException
from fastapi.responses import FileResponse, StreamingResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, Field

from app.web.presentation import STAGES, commands_for_status, option_view

STATIC = Path(__file__).resolve().parent / "static"
app = FastAPI(title="Travel Negotiator", version="0.1.0", docs_url=None, redoc_url=None)
app.mount("/static", StaticFiles(directory=STATIC), name="static")
_agent_lock = RLock()  # InMemorySaver is process local: one worker for demo.


@lru_cache(maxsize=1)
def get_agent():
    from app.agent.graph_agent import GraphTravelAgent
    from app.agent.mcp_search import McpCatalogSearch
    from app.agent.mcp_booking import McpCatalogBooking
    from app.agent.compact_parser import CompactYandexTurnParser
    from app.agent.text_provider import YandexTextGenerator
    return GraphTravelAgent(CompactYandexTurnParser(), YandexTextGenerator(),
                            search=McpCatalogSearch(), booking=McpCatalogBooking())


class ChatInput(BaseModel):
    session_id: UUID
    message: str = Field(min_length=1, max_length=4000)


@app.get("/", include_in_schema=False)
def home():
    return FileResponse(STATIC / "index.html", headers={"Cache-Control": "no-store"})


@app.get("/api/catalog/history")
def historical_catalog(destination_id: str | None = None, limit: int = 20):
    """Historical-only observations; deliberately not selectable for booking."""
    from app.data.snapshot_catalog import SnapshotCatalogProvider
    results = SnapshotCatalogProvider().search(destination_id=destination_id)
    return {"data_type": "historical_not_live", "count": len(results),
            "items": [r.model_dump(mode="json") for r in results[:max(1, min(limit, 100))]]}


@app.get("/health")
@app.get("/api/health")
def health():
    return {"status": "ok", "mode": "synthetic-demo"}


def _serialize_reply(reply):
    options = [option_view(item) for item in reply.options]
    # Explicit actions are generated by the server; the browser does not compose permissions.
    commands = [{"label": label, "message": command}
                for label, command in commands_for_status(reply.status, len(options), len(reply.compromises))]
    return {
        "status": reply.status,
        "status_label": STAGES.get(reply.status, reply.status),
        "message": reply.message,
        "version": reply.version,
        "options": options,
        "compromises": [{"kind": str(c.get("kind", "")),
                         "description": str(c.get("description", "")),
                         "price": option_view({"price_rub": c.get("price_rub")})["price"]}
                        for c in reply.compromises],
        "commands": commands,
        "disclaimer": "Демонстрационный каталог: предложения, цены и доступность синтетические; реальная бронь не оформляется.",
    }


def _validated_message(payload: ChatInput) -> str:
    message = payload.message.strip()
    if not message:
        raise HTTPException(422, "Сообщение не должно быть пустым")
    return message


@app.post("/api/chat")
def chat(payload: ChatInput):
    message = _validated_message(payload)
    try:
        with _agent_lock:
            reply = get_agent().handle(str(payload.session_id), message)
    except Exception:
        logging.getLogger(__name__).warning("Chat request failed: %s", type(sys.exc_info()[1]).__name__)
        raise HTTPException(503, "Не удалось обработать запрос. Попробуйте позже.") from None
    return _serialize_reply(reply)


def _sse(event: str, value: dict) -> str:
    return f"event: {event}\ndata: {json.dumps(value, ensure_ascii=False)}\n\n"


@app.post("/api/chat/stream")
def stream_chat(payload: ChatInput):
    message = _validated_message(payload)

    def events():
        # Run the same graph once; progress events report completed graph nodes,
        # not fabricated LLM tokens or unvalidated recommendations.
        yield _sse("progress", {"stage": "start", "message": "Обрабатываю запрос…"})
        try:
            with _agent_lock:
                agent = get_agent()
                for update in agent.stream_updates(str(payload.session_id), message):
                    if update[0] == "done":
                        yield _sse("result", _serialize_reply(update[1]))
                    else:
                        yield _sse("progress", {"stage": update[0], "message": update[1]})
        except Exception:
            logging.getLogger(__name__).warning("Streaming chat request failed: %s", type(sys.exc_info()[1]).__name__)
            yield _sse("error", {"message": "Не удалось обработать запрос. Попробуйте позже."})

    return StreamingResponse(events(), media_type="text/event-stream", headers={
        "Cache-Control": "no-cache, no-transform", "X-Accel-Buffering": "no"})


@app.middleware("http")
async def no_cache_static(request, call_next):
    response = await call_next(request)
    if request.url.path.startswith("/static/"):
        response.headers["Cache-Control"] = "no-store, max-age=0"
    return response
