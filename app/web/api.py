"""Local demo FastAPI frontend, built on the existing LangGraph/MCP agent."""

from __future__ import annotations

import json
import logging
import sys
from contextlib import asynccontextmanager
from pathlib import Path
from uuid import UUID, uuid4

from fastapi import FastAPI, HTTPException, Response
from fastapi.responses import FileResponse, StreamingResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, Field

from app.containers import ApplicationContainer
from app.observability import event as audit_event
from app.observability import turn_context, user_message_value
from app.web.presentation import STAGES, commands_for_status, option_view

STATIC = Path(__file__).resolve().parent / "static"
container = ApplicationContainer()


@asynccontextmanager
async def lifespan(_: FastAPI):
    yield
    container.close()


app = FastAPI(
    title="Travel Negotiator",
    version="0.1.0",
    docs_url=None,
    redoc_url=None,
    lifespan=lifespan,
)
app.mount("/static", StaticFiles(directory=STATIC), name="static")
_agent_lock = container.agent_lock


def get_agent():
    return container.agent


class ChatInput(BaseModel):
    session_id: UUID
    message: str = Field(min_length=1, max_length=4000)


@app.get("/", include_in_schema=False)
def home():
    return FileResponse(STATIC / "index.html", headers={"Cache-Control": "no-store"})


@app.get("/api/catalog/history")
def historical_catalog(destination_id: str | None = None, limit: int = 20):
    """Historical-only observations; deliberately not selectable for booking."""
    from app.data.snapshot_catalog import SnapshotCatalogProvider

    results = SnapshotCatalogProvider().search(destination_id=destination_id)
    return {
        "data_type": "historical_not_live",
        "count": len(results),
        "items": [r.model_dump(mode="json") for r in results[: max(1, min(limit, 100))]],
    }


@app.get("/health")
@app.get("/api/health")
def health():
    return {"status": "ok", "mode": "synthetic-demo"}


def _serialize_reply(reply):
    options = [option_view(item) for item in reply.options]
    active_skill = getattr(reply, "active_skill", None)
    # Explicit actions are generated by the server; the browser does not compose permissions.
    commands = [
        {"label": label, "message": command}
        for label, command in commands_for_status(
            reply.status, len(options), len(reply.compromises)
        )
    ]
    return {
        "status": reply.status,
        "status_label": STAGES.get(reply.status, reply.status),
        "message": reply.message,
        "version": reply.version,
        "active_skill": active_skill.value if active_skill else None,
        "options": options,
        "compromises": [
            {
                "kind": str(c.get("kind", "")),
                "description": str(c.get("description", "")),
                "price": option_view({"price_rub": c.get("price_rub")})["price"],
            }
            for c in reply.compromises
        ],
        "commands": commands,
        "disclaimer": (
            "Демонстрационный каталог: предложения, цены и доступность "
            "синтетические; реальная бронь не оформляется."
        ),
    }


def _validated_message(payload: ChatInput) -> str:
    message = payload.message.strip()
    if not message:
        raise HTTPException(422, "Сообщение не должно быть пустым")
    return message


@app.post("/api/chat")
def chat(payload: ChatInput, response: Response):
    message = _validated_message(payload)
    request_id = str(uuid4())
    response.headers["X-Request-ID"] = request_id
    try:
        with turn_context(request_id, str(payload.session_id)):
            audit_event("chat.received", transport="http", message=user_message_value(message))
            with _agent_lock:
                reply = get_agent().handle(str(payload.session_id), message)
            audit_event(
                "chat.completed",
                status=reply.status,
                version=reply.version,
                response=reply.message,
                options_count=len(reply.options),
                compromises_count=len(reply.compromises),
            )
    except Exception:
        logging.getLogger(__name__).warning(
            "Chat request failed: %s", type(sys.exc_info()[1]).__name__
        )
        raise HTTPException(503, "Не удалось обработать запрос. Попробуйте позже.") from None
    return _serialize_reply(reply)


def _sse(event: str, value: dict) -> str:
    return f"event: {event}\ndata: {json.dumps(value, ensure_ascii=False)}\n\n"


@app.post("/api/chat/stream")
def stream_chat(payload: ChatInput):
    message = _validated_message(payload)
    request_id = str(uuid4())

    def events():
        # Progress events correspond to completed graph nodes.
        with turn_context(request_id, str(payload.session_id)):
            audit_event("chat.received", transport="sse", message=user_message_value(message))
            yield _sse(
                "progress",
                {
                    "stage": "start",
                    "message": "Обрабатываю запрос…",
                    "request_id": request_id,
                },
            )
            try:
                with _agent_lock:
                    agent = get_agent()
                    for update in agent.stream_updates(str(payload.session_id), message):
                        if update[0] == "done":
                            audit_event(
                                "chat.completed",
                                status=update[1].status,
                                version=update[1].version,
                                response=update[1].message,
                                options_count=len(update[1].options),
                                compromises_count=len(update[1].compromises),
                            )
                            yield _sse("result", _serialize_reply(update[1]))
                        else:
                            yield _sse("progress", {"stage": update[0], "message": update[1]})
            except Exception:
                logging.getLogger(__name__).warning(
                    "Streaming chat request failed: %s",
                    type(sys.exc_info()[1]).__name__,
                )
                audit_event(
                    "chat.failed",
                    level=logging.ERROR,
                    error_type=type(sys.exc_info()[1]).__name__,
                )
                yield _sse(
                    "error",
                    {"message": "Не удалось обработать запрос. Попробуйте позже."},
                )

    return StreamingResponse(
        events(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache, no-transform",
            "X-Accel-Buffering": "no",
            "X-Request-ID": request_id,
        },
    )


@app.middleware("http")
async def no_cache_static(request, call_next):
    response = await call_next(request)
    if request.url.path.startswith("/static/"):
        response.headers["Cache-Control"] = "no-store, max-age=0"
    return response
